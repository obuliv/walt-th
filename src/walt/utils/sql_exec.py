"""Shared in-memory SQLite executor.

Runs a list of context statements (typically CREATE TABLE / INSERT INTO) followed by a
SQL query against a fresh in-memory SQLite database. Used both to locally verify the
sql_context generated by gen_training_data.py and to execute an agent's chosen SQL
candidate.
"""
from __future__ import annotations

import sqlite3
from dataclasses import dataclass
from typing import Sequence


@dataclass(frozen=True)
class ExecutionResult:
    success: bool
    columns: tuple[str, ...] | None
    rows: tuple[tuple, ...] | None
    error: str | None


def run_sql(context_statements: Sequence[str], sql: str, timeout: float = 5.0) -> ExecutionResult:
    conn = sqlite3.connect(":memory:", timeout=timeout)
    try:
        cursor = conn.cursor()
        for statement in context_statements:
            cursor.execute(statement)
        cursor.execute(sql)
        if cursor.description is not None:
            columns = tuple(col[0] for col in cursor.description)
            rows = tuple(cursor.fetchall())
        else:
            columns, rows = None, None
        conn.commit()
        return ExecutionResult(success=True, columns=columns, rows=rows, error=None)
    except sqlite3.Error as exc:
        return ExecutionResult(success=False, columns=None, rows=None, error=str(exc))
    finally:
        conn.close()
